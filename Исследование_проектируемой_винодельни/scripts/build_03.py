def simple_list(name, items, title, note):
    ws = wb.create_sheet(name)
    style_title(ws, "A1", title)
    ws["A2"] = note
    hh = ["Участок", "Наименование", "Производитель", "Модель", "Pном, кВт", "U, В", "Производительность", "Статус", "Ссылка", "Стр.", "Примечание"]
    ws.append([])
    ws.append(hh)
    style_header(ws, 4, len(hh))
    for s, i in items:
        x = SRC[s][i]
        ws.append([x.get("участок"), x.get("наименование"), x.get("производитель"), x.get("модель"), x.get("p_kw"), x.get("u_v"),
                   x.get("производительность"), x.get("статус"), x.get("url"), x.get("стр"), x.get("примечание")])
    for row in ws.iter_rows(min_row=4, max_row=ws.max_row, max_col=len(hh)):
        for c in row:
            c.border = thin
            c.alignment = wrap
    autowidth(ws, {"A": 16, "B": 30, "C": 18, "D": 24, "E": 9, "F": 12, "G": 24, "H": 18, "I": 40, "J": 14, "K": 60})


