def months_set(s):
    if s.startswith("Круглый"):
        return set(range(1, 13))
    m = re.match(r"([IVX]+)–([IVX]+)", s)
    if not m:
        return set()
    a, b = ROMAN[m.group(1)], ROMAN[m.group(2)]
    return set(range(a, b + 1)) if a <= b else set(range(a, 13)) | set(range(1, b + 1))


def flags(t):
    ms = months_set(t[7])
    s, l, w = int(9 in ms), int(7 in ms), int(1 in ms)
    if t[2] == "Розлив" and t[1] != "alc":
        s = 0      # розлив вне сезона переработки
    return s, l, w


def cat_num(c):
    return 1 if c.startswith("I ") or c == "I" else (3 if c.startswith("III") else 2)


def get(src, idx):
    return SPECIAL[idx] if src is None else SRC[src][idx]


def first(x, *keys):
    for k in keys:
        v = x.get(k)
        if v not in (None, ""):
            return v
    return None


