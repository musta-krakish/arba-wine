def md_table(md_text, header_start):
    lines = md_text.splitlines()
    for i, ln in enumerate(lines):
        if ln.startswith(header_start):
            out = []
            for ln2 in lines[i:]:
                if not ln2.startswith("|"):
                    break
                if re.match(r"^\|[-\s|]+\|$", ln2):
                    continue
                out.append([c.strip().replace("**", "") for c in ln2.strip().strip("|").split("|")])
            return out
    return []


