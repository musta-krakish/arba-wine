def p_of(t):
    src, idx = t[0], t[1]
    if t[11] == "LIGHT":
        return LIGHT
    if t[11] is not None:
        return t[11] * t[4]
    if src is None:
        return 0.0
    p = SRC[src][idx].get("p_kw")
    return (p or 0.0) * t[4]


