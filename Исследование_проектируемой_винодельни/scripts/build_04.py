def H(*spans, v=1.0, base=None):
    """Профиль 24 ч: spans — (начало, конец) часов, значение v; base — значение в остальные часы."""
    out = [base or 0.0] * 24
    for a, b in spans:
        for h in range(a, b):
            out[h % 24] = v
    return out


def mix(*profiles):
    out = [0.0] * 24
    for p in profiles:
        out = [max(a, b) for a, b in zip(out, p)]
    return out


