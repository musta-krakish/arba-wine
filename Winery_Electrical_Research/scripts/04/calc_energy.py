"""Годовое электропотребление учебного варианта: E = Pном · n_раб · Kзагр · T (все часы — допущения, см. 04_Электроснабжение.md)."""
import json, sys
V = json.load(open(sys.argv[1]))
def f(x):
    try: return float(x)
    except (TypeError, ValueError): return None
SEZ_PR = 45*10      # приёмка: 45 дней × 10 ч (ВНТП 25-85: приёмка 10 ч/сут)
SEZ_PER = 45*16     # переработка/прессование: 2 смены по 8 ч (ВНТП 25-85)
FERM = 75*24        # брожение и активное охлаждение: ≈75 суток × 24 ч (20.08 – начало ноября)
OFF = (365-75)*24   # межсезонье, круглосуточно
WD = 250*8          # 1 смена, 250 рабочих дней
BOT = 50*8          # розлив: ≈933 тыс. бут./год ÷ 2 500 бут/ч ÷ 8 ч ≈ 47 → 50 дней
# Чиллер: 45 сут пика брожения при Ки + 30 сут «хвоста» при 0,3 + межсезонье 0,15 (по AWRI Winery A: вне сезона холод ≈370 кВт·ч/сут на 500 т).
# Внутреннее освещение: 250 дн × 8 ч + 75 дн сезона × 8 ч второй смены.
# (подстрока наименования) -> список (часы, коэффициент загрузки относительно Pном·n_раб); None — брать Ки
RULES = [
 ("Бункер", [(SEZ_PR,None)]), ("Вибростол", [(SEZ_PR,None)]), ("Сортировочная", [(SEZ_PR,None)]), ("элеватор", [(SEZ_PR,None)]),
 ("Гребнеотделитель", [(SEZ_PR,None)]), ("Насос мезги", [(SEZ_PR,None)]),
 ("Пневмопресс", [(SEZ_PER,None)]), ("Шнек выгрузки", [(SEZ_PER,None)]), ("Флотатор", [(SEZ_PER,None)]),
 ("Чиллер", [(45*24,None),(30*24,0.3),(OFF,0.15)]), ("Насос гликолевого", [(FERM,None),(OFF,0.8)]),
 ("кулачковый", [(FERM//3,None),(WD//2,None)]), ("Импеллерный", [(FERM//3,None),(WD//4,None)]), ("Мешалка", [(FERM//4,None),(WD//4,None)]),
 ("общеобменная", [(FERM,None)]),
 ("Намывной", [(WD//2,None)]), ("Тангенциальный", [(WD//2,None)]), ("азота", [(WD,None)]), ("компрессор", [(SEZ_PER,None),(WD,0.4)]),
 ("бутылочного погреба", [(8760,None)]),
 ("Моноблок", [(BOT,None)]), ("Мойка-сушка", [(BOT,None)]), ("Капсулятор", [(BOT,None)]), ("Этикетировщик", [(BOT,None)]),
 ("Конвейеры", [(BOT,None)]), ("Маркиратор", [(BOT,None)]), ("Заклейщик", [(BOT,None)]), ("Стретч", [(BOT,None)]),
 ("Зарядное", [(WD,None)]), ("Электропарогенератор", [(300,1.0)]), ("Скважинный", [(WD,None),(FERM,0.3)]), ("осмоса", [(WD,None)]),
 ("горелки", [(180*24,None)]), ("Лабораторное", [(WD,None)]),
 ("Внутреннее освещение", [(250*8+75*8,None)]), ("Наружное освещение", [(4000,None)]),
]
tot = 0; rows = []
for x in V:
    p, n, rez, ki = f(x["p"]), f(x["cnt"]), f(x["rez"]) or 0, f(x["ki"])
    if p is None or n - rez <= 0: continue
    rule = next((r for k, r in RULES if k.lower() in x["name"].lower()), None)
    assert rule, x["name"]
    e = sum(p*(n-rez)*(k if k is not None else ki)*h for h, k in rule)/1000
    rows.append((x["cex"], x["name"], p*(n-rez), e)); tot += e
grp = {}
for c, nm, P, e in rows:
    key = {"Приёмное отделение":"Приёмка и прессование","Прессовое отделение":"Приёмка и прессование","Холодильная станция":"Холод (чиллер, гликоль)",
           "Бродильное отделение":"Бродильное отделение","Отделение обработки":"Обработка, азот, сжатый воздух","Компрессорная":"Обработка, азот, сжатый воздух",
           "Склад готовой продукции":"Розлив и склад","Освещение":"Освещение"}.get(c, "Розлив и склад" if c.startswith("Цех розлива") else "Вспомогательные (мойка, вода, погреба, котельная, лаборатория)")
    grp[key] = grp.get(key, 0) + e
for k, v in sorted(grp.items(), key=lambda t: -t[1]): print(f"{k:60s} {v:7.1f} МВт·ч  {v/tot*100:5.1f} %")
print(f"{'ИТОГО':60s} {tot:7.1f} МВт·ч")
print(f"Удельно: {tot*1000/1000:.0f} кВт·ч/т винограда; {tot*1000/7000:.1f} кВт·ч/гл (при 7 000 гл)")
print(f"Tmax = W/Pр = {tot*1000/188.8:.0f} ч (Pр = 188,8 кВт)")
